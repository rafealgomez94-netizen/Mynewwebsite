import { handleError } from '@/lib/api/http';
import { getSessionContext } from '@/lib/auth/session';
import { assertPermission, HttpError, requireTenant } from '@/lib/auth/rbac';
import { findDocument } from '@/lib/db/repositories/content';
import { findBusinessById } from '@/lib/db/repositories/accounts';
import { buildPdf, type PdfBlock } from '@/lib/services/pdf';
import { formatDate, formatMoney } from '@/lib/utils';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

type Params = { params: Promise<{ id: string }> };

export async function GET(_request: Request, { params }: Params) {
  try {
    const { id } = await params;
    const ctx = requireTenant(await getSessionContext());
    assertPermission(ctx, 'documents:read');
    const document = findDocument(ctx.business.id, id);
    if (!document) throw new HttpError(404, 'Document not found.', 'not_found');
    const business = findBusinessById(ctx.business.id);

    const content = document.content as {
      sections?: { heading: string; body: string }[];
      lines?: { name: string; quantity: number; unitPriceCents: number; totalCents: number }[];
      subtotalCents?: number;
      totalCents?: number;
    };

    const blocks: PdfBlock[] = [
      { type: 'title', text: document.title },
      {
        type: 'subtitle',
        text: `${document.number} · ${document.type} · issued ${formatDate(document.created_at)}`,
      },
      { type: 'spacer', height: 6 },
      { type: 'heading', text: 'From' },
      { type: 'paragraph', text: `${business?.name ?? ''}${business?.phone ? `\n${business.phone}` : ''}${business?.email ? `\n${business.email}` : ''}${business?.address ? `\n${business.address}, ${business.city ?? ''}` : ''}` },
    ];

    if (document.customer_name) {
      blocks.push({ type: 'heading', text: 'Customer' }, { type: 'paragraph', text: document.customer_name });
    }

    if (content.sections?.length) {
      for (const section of content.sections) {
        blocks.push({ type: 'heading', text: section.heading }, { type: 'paragraph', text: section.body });
      }
    } else if (document.content_text) {
      blocks.push({ type: 'paragraph', text: document.content_text });
    }

    if (content.lines?.length) {
      blocks.push({ type: 'heading', text: 'Line items' });
      blocks.push({
        type: 'table',
        columns: ['Description', 'Qty', 'Unit price', 'Total'],
        columnWidths: [250, 50, 100, 100],
        rows: content.lines.map((line) => [
          line.name,
          String(line.quantity),
          formatMoney(line.unitPriceCents, document.currency),
          formatMoney(line.totalCents, document.currency),
        ]),
      });
      blocks.push({
        type: 'kv',
        label: 'Subtotal',
        value: formatMoney(content.subtotalCents ?? content.totalCents ?? 0, document.currency),
      });
      blocks.push({ type: 'kv', label: 'Total', value: formatMoney(content.totalCents ?? 0, document.currency) });
    }

    if (document.due_at) {
      blocks.push({ type: 'kv', label: 'Due date', value: formatDate(document.due_at) });
    }
    blocks.push({ type: 'spacer' }, { type: 'paragraph', text: `Status: ${document.status}` });

    const pdfBytes = await buildPdf(blocks, `${business?.name ?? 'Workspace Digital'} · ${document.number} · generated by Workspace Digital`);

    return new Response(Buffer.from(pdfBytes), {
      headers: {
        'content-type': 'application/pdf',
        'content-disposition': `attachment; filename="${document.number}-${document.title.replace(/[^a-z0-9]+/gi, '-').slice(0, 40)}.pdf"`,
        'cache-control': 'no-store',
      },
    }) as unknown as ReturnType<typeof Response.json>;
  } catch (error) {
    return handleError(error);
  }
}
