import { handleError } from '@/lib/api/http';
import { getSessionContext } from '@/lib/auth/session';
import { assertPermission, HttpError, requireTenant } from '@/lib/auth/rbac';
import { findReport } from '@/lib/db/repositories/ops';
import { findBusinessById } from '@/lib/db/repositories/accounts';
import { buildPdf, type PdfBlock } from '@/lib/services/pdf';
import { formatDate, formatMoney } from '@/lib/utils';
import type { ReportMetrics } from '@/lib/services/reports';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

type Params = { params: Promise<{ id: string }> };

export async function GET(_request: Request, { params }: Params) {
  try {
    const { id } = await params;
    const ctx = requireTenant(await getSessionContext());
    assertPermission(ctx, 'reports:read');
    const report = findReport(ctx.business.id, id);
    if (!report) throw new HttpError(404, 'Report not found.', 'not_found');
    const business = findBusinessById(ctx.business.id);
    const metrics = report.metrics as unknown as ReportMetrics;

    const blocks: PdfBlock[] = [
      { type: 'title', text: report.title },
      {
        type: 'subtitle',
        text: `${formatDate(metrics.periodStart)} → ${formatDate(metrics.periodEnd)} · source: ${
          report.summary_source === 'AI' ? 'calculated metrics + AI narrative' : 'calculated metrics'
        }`,
      },
      { type: 'heading', text: 'Calculated from stored data' },
      { type: 'kv', label: 'Revenue', value: formatMoney(metrics.revenueCents) },
      {
        type: 'kv',
        label: 'Change vs previous',
        value: `${metrics.revenueChangePct >= 0 ? '+' : ''}${metrics.revenueChangePct.toFixed(1)}%`,
      },
      { type: 'kv', label: 'Orders', value: String(metrics.orders) },
      { type: 'kv', label: 'Average order', value: formatMoney(metrics.averageOrderCents) },
      { type: 'kv', label: 'New customers', value: String(metrics.newCustomers) },
      { type: 'kv', label: 'Total customers', value: String(metrics.totalCustomers) },
      {
        type: 'kv',
        label: 'Appointments',
        value: `${metrics.appointments.total} total · ${metrics.appointments.completed} completed · ${metrics.appointments.cancelled} cancelled`,
      },
      {
        type: 'kv',
        label: 'Support',
        value: `${metrics.support.openConversations} open conversations · ${metrics.support.openTickets} open tickets`,
      },
    ];

    if (metrics.topItems.length) {
      blocks.push({ type: 'heading', text: 'Top items' });
      blocks.push({
        type: 'table',
        columns: ['Item', 'Units', 'Revenue'],
        columnWidths: [300, 80, 120],
        rows: metrics.topItems.map((item) => [item.name, String(item.units), formatMoney(item.revenueCents)]),
      });
    }

    if (metrics.lowStock.length) {
      blocks.push({ type: 'heading', text: 'Inventory attention' });
      blocks.push({ type: 'table', columns: ['Product', 'In stock', 'Minimum'], columnWidths: [300, 100, 100], rows: metrics.lowStock.map((product) => [product.name, String(product.quantity), String(product.minStock)]) });
    }

    if (metrics.leads.length) {
      blocks.push({ type: 'heading', text: 'Sales pipeline' });
      blocks.push({
        type: 'table',
        columns: ['Stage', 'Leads', 'Value'],
        columnWidths: [220, 80, 200],
        rows: metrics.leads.map((lead) => [lead.stage.replace('_', ' '), String(lead.count), formatMoney(lead.valueCents)]),
      });
    }

    if (report.ai_summary) {
      blocks.push({
        type: 'heading',
        text: report.summary_source === 'AI' ? 'AI narrative (recommendations)' : 'Summary',
      });
      blocks.push({ type: 'paragraph', text: report.ai_summary });
    }

    if (metrics.recommendations?.length) {
      blocks.push({ type: 'heading', text: 'AI recommendations' });
      for (const recommendation of metrics.recommendations.slice(0, 8)) {
        blocks.push({ type: 'paragraph', text: `• ${recommendation}` });
      }
    }

    const pdfBytes = await buildPdf(
      blocks,
      `${business?.name ?? 'Workspace Digital'} · ${report.period} report · generated by Workspace Digital`,
    );

    return new Response(Buffer.from(pdfBytes), {
      headers: {
        'content-type': 'application/pdf',
        'content-disposition': `attachment; filename="${report.period.toLowerCase()}-report-${report.period_start.slice(0, 10)}.pdf"`,
        'cache-control': 'no-store',
      },
    }) as unknown as ReturnType<typeof Response.json>;
  } catch (error) {
    return handleError(error);
  }
}
